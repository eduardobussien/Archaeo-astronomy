# Keeps every requested date, and the heliacal scan's previous-year start, inside the model.
YEAR_RANGE = (math.ceil(EPOCH_RANGE[0]) + 2, math.floor(EPOCH_RANGE[1]) - 2)
_SITE_NAMES = {name.lower(): name for name in MONUMENTS}


class ApiError(Exception):
    """A request the API cannot serve; reported to the client as JSON."""

    def __init__(self, message, status=400):
        super().__init__(message)
        self.status = status


@app.errorhandler(ApiError)
def handle_api_error(err):
    return jsonify({'error': str(err)}), err.status


@app.errorhandler(500)
def handle_server_error(err):
    if request.path.startswith('/api/'):
        return jsonify({'error': 'Internal server error'}), 500
    return err


def _number(name, default, cast, low, high):
    raw = request.args.get(name)
    if raw is None:
        return default
    kind = 'a whole number' if cast is int else 'a number'
    try:
        value = cast(raw)
    except ValueError:
        raise ApiError(f"'{name}' must be {kind}") from None
    if not (math.isfinite(value) and low <= value <= high):
        raise ApiError(f"'{name}' must be between {low} and {high}")
    return value


def _flag(name, default):
    raw = request.args.get(name)
    if raw is None:
        return default
    if raw.lower() in ('1', 'true'):
        return True
    if raw.lower() in ('0', 'false'):
        return False
    raise ApiError(f"'{name}' must be 0 or 1")


def _location():
    """(lat, lon, elevation in metres, monument name or None) from ?site= or ?lat=&lon=&elevation=."""
    site = request.args.get('site')
    if site:
        name = _SITE_NAMES.get(site.strip().lower())
        if name is None:
            raise ApiError("Unknown site; see /api/sites for the list", 404)
        m = MONUMENTS[name]
        return m['lat'], m['lon'], m['elevation_m'], name
    return (_number('lat', 29.9792, float, -90.0, 90.0),
            _number('lon', 31.1342, float, -180.0, 180.0),
            _number('elevation', 0.0, float, -500.0, 9000.0),
            None)


def _calendar():
    calendar = request.args.get('calendar', 'gregorian').lower()
    if calendar not in CALENDARS:
        raise ApiError("'calendar' must be 'gregorian' or 'julian'")
    return calendar


def _date_time():
    """(year, month, day, hour, calendar): astronomical year, date in that calendar, local hour."""
    calendar = _calendar()
    year = _number('year', -2499, int, *YEAR_RANGE)
    month = _number('month', 3, int, 1, 12)
    day = _number('day', 20, int, 1, days_in_month(year, month, calendar))
    hour = _number('hour', 22.0, float, 0.0, 24.0)
    return year, month, day, hour, calendar


def _horizon(default=0.0):
    """The skyline from ?horizon=: a number for a level horizon, or a profile 'az:alt,az:alt,...'."""
    raw = request.args.get('horizon')
    if raw is None or ':' not in raw:
        return HorizonProfile([0.0], [_number('horizon', default, float, *ALTITUDE_RANGE)])
    try:
        return HorizonProfile.from_compact(raw)
    except ValueError as err:
        raise ApiError(str(err)) from None


def _format():
    fmt = request.args.get('format', 'json').lower()
    if fmt not in ('json', 'csv'):
        raise ApiError("'format' must be 'json' or 'csv'")
    return fmt


_MONTHS = ('', 'January', 'February', 'March', 'April', 'May', 'June', 'July', 'August',
           'September', 'October', 'November', 'December')


def _clock(hour):
    minutes = round(hour * 60)
    return f'{minutes // 60:02d}:{minutes % 60:02d}'


def _provenance(lat, lon, elevation, site, refract, calendar):
    """The '#' header lines every CSV starts with, so the file says how it was made."""
    return {
        'generated by': 'Archaeo-Astronomy Sky Explorer, https://github.com/eduardobussien/Archaeo-astronomy',
        'generated on': datetime.date.today().isoformat(),
        'request': request.full_path,
        'site': site or 'custom coordinates',
        'latitude_deg': lat,
        'longitude_deg': lon,
        'elevation_m': elevation,
        'refraction': 'on (apparent altitudes)' if refract else 'off (geometric altitudes)',
        'calendar': f'{calendar} (proleptic)',
        'accuracy': 'see docs/ACCURACY.md in the repository',
    }


def _csv(filename, header, columns, rows):
    """A CSV download: '# key: value' lines (pandas: comment='#'), then the table."""
    out = io.StringIO()
    for key, value in header.items():
        out.write(f'# {key}: {value}\n')
    writer = csv.writer(out, lineterminator='\n')
    writer.writerow(columns)
    writer.writerows(rows)
    return Response(out.getvalue(), mimetype='text/csv',
                    headers={'Content-Disposition': f'attachment; filename="{filename}"'})


